import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const origin = 'https://fridaunddiego.com/';
const pages = {
    'index.html': ['Frida & Diego | Mexikanisches Restaurant & Cocktailbar in Schöneberg', 'Mexikanische Küche, Tex-Mex und Cocktails bei Frida & Diego in Berlin-Schöneberg. Entdecke die Speisekarte und reserviere in der Fuggerstraße 28.'],
    'menu.html': ['Speise- und Cocktailkarte | Frida & Diego Berlin-Schöneberg', 'Die Speisekarte von Frida & Diego in Berlin-Schöneberg mit mexikanischen Gerichten, Cocktails, alkoholfreien Drinks und Preisen.'],
    'reservation.html': ['Tischreservierung | Frida & Diego Berlin-Schöneberg', 'Frage einen Tisch bei Frida & Diego, dem mexikanischen Restaurant mit Cocktailbar in der Fuggerstraße 28, an.'],
    'workshops.html': ['Private Cocktail-Workshops | Frida & Diego Berlin', 'Lerne in Berlin-Schöneberg mit unserem Barkeeper, drei Cocktails zu mixen. Frage einen privaten Gruppenworkshop an.'],
    "cocktails.html": ["Margaritas & Cocktails in Berlin-Schöneberg | Frida & Diego","Entdecke Margaritas, Palomas und alkoholfreie Cocktails bei Frida & Diego in Berlin-Schöneberg."],
    "mexican-food.html": ["Mexikanisch essen in Berlin-Schöneberg | Frida & Diego","Entdecke mexikanische Gerichte, Tex-Mex, Gemüseoptionen und die Anfahrt zu Frida & Diego in Schöneberg."]
};
const files = Object.keys(pages);
const sitemap = [];
mkdirSync('de', { recursive: true });

for (const [file, [title, description]] of Object.entries(pages)) {
    const en = origin + (file === 'index.html' ? '' : file);
    const de = origin + 'de/' + file;
    const alternates = [['en', en], ['de', de], ['x-default', en]]
        .map(([lang, url]) => '    <link rel="alternate" hreflang="' + lang + '" href="' + url + '">').join('\n');
    let html = readFileSync(file, 'utf8').replace(/\n    <link rel="alternate" hreflang="[^"]+" href="[^"]+">/g, '');
    html = html.replace(/(<link rel="canonical" href="[^"]+">)/, '$1\n' + alternates);
    html = html.replace(/<(?:button|a) class="(lang-toggle(?:-mini)?)" id="lang-toggle"[^>]*>[\s\S]*?<\/(?:button|a)>/,
        (_, cls) => '<a class="' + cls + '" id="lang-toggle" href="de/' + file + '" hreflang="de" lang="de" aria-label="Auf Deutsch lesen"><span class="lang-active">EN</span> / <span class="lang-inactive">DE</span></a>');
    writeFileSync(file, html);

    const localized = html.replace('<html lang="en">', '<html lang="de">')
        .replace(/<title>[^<]*<\/title>/, '<title>' + title.replaceAll('&', '&amp;') + '</title>')
        .replace(/<meta name="description" content="[^"]*">/, '<meta name="description" content="' + description + '">')
        .replace('rel="canonical" href="' + en + '"', 'rel="canonical" href="' + de + '"')
        .replace(/<([a-z][\w-]*)((?:"[^"]*"|'[^']*'|[^'">])*\sdata-de="([^"]*)"(?:"[^"]*"|'[^']*'|[^'">])*)>([\s\S]*?)<\/\1>/gi,
            (_, tag, attrs, german, previous) => '<' + tag + attrs + '>' + german + (tag === 'label' && /\s\*$/.test(previous) ? ' *' : '') + '</' + tag + '>')
        .replace(/\b(href|src)="([^"]+)"/g, (match, attr, path) => {
            if (/^(?:[a-z]+:|#|\/)/i.test(path) || files.includes(path.split(/[?#]/)[0])) return match;
            return attr + '="../' + path + '"';
        })
        .replace(/<a class="(lang-toggle(?:-mini)?)" id="lang-toggle"[^>]*>[\s\S]*?<\/a>/,
            (_, cls) => '<a class="' + cls + '" id="lang-toggle" href="../' + (file === 'index.html' ? '' : file) + '" hreflang="en" lang="en" aria-label="Read in English"><span class="lang-active">DE</span> / <span class="lang-inactive">EN</span></a>');
    writeFileSync('de/' + file, '<!-- Generated by scripts/build-german.mjs. Edit the root HTML and regenerate. -->\n' + localized.replace(/[ \t]+$/gm, ''));
    sitemap.push(en, de);
}
writeFileSync('sitemap.xml', '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
    sitemap.map(url => '  <url><loc>' + url + '</loc></url>').join('\n') + '\n</urlset>\n');
